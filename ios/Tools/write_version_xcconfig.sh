#!/bin/sh
# Scheme pre-action (Lightly › Build › Pre-actions): writes ios/Lightly/Version.generated.xcconfig from
# scripts/version.sh so Xcode IDE builds and archives get the real version and build number (see Lightly.xcconfig).
# App Store versions must be numeric, so an uncommitted tree's "1.0.0-dev" is written as "1.0.0" with a warning in
# the build log: such an archive is not the commit it names and should not be uploaded.
set -u
ios_dir="${PROJECT_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
repo="$(cd "$ios_dir/.." && pwd)"
out="$ios_dir/Lightly/Version.generated.xcconfig"
if version=$(sh "$repo/scripts/version.sh" 2>/dev/null); then
    marketing="${version% *}"; build="${version#* }"
    case "$marketing" in *-dev) echo "warning: uncommitted changes in ios/, android/ or shared/; this build is not commit $(git -C "$repo" rev-parse --short HEAD)";; esac
    printf '// Generated by Tools/write_version_xcconfig.sh; do not edit or commit.\nMARKETING_VERSION = %s\nCURRENT_PROJECT_VERSION = %s\n' "${marketing%-dev}" "$build" > "$out"
fi
